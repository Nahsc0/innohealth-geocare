CREATE TABLE IF NOT EXISTS communities (
 id VARCHAR(64) PRIMARY KEY, name VARCHAR(120) NOT NULL, state VARCHAR(80) NOT NULL,
 lga VARCHAR(80) NOT NULL, lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
 population INTEGER, source TEXT NOT NULL, verified_at VARCHAR(10) NOT NULL
);
CREATE INDEX IF NOT EXISTS communities_area ON communities(state,lga);
